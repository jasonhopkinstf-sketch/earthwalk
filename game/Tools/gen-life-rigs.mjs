// Writes game/Source/EarthWalk/EarthLifeRigs.gen.inl from server/public/js/liferigs.js, so the
// Windows game draws every animal and vehicle from the very tables the browser uses.
//
//   node game/Tools/gen-life-rigs.mjs
//
// Run it again whenever liferigs.js changes, and commit the result.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const { RIGS, VEHICLES } = await import(pathToFileURL(join(here, "../../server/public/js/liferigs.js")).href);

const num = (n) => {
  if (!Number.isFinite(n)) throw new Error(`not a number: ${n}`);
  const s = String(n);
  return /[.e]/.test(s) ? s : `${s}.0`;
};
const hex = (n) => `0x${(n >>> 0).toString(16).padStart(6, "0")}`;
const vec = (v) => `{ ${v.map(num).join(", ")} }`;
const text = (s) => (s ? `TEXT("${s}")` : "nullptr");
const SHAPES = { sphere: "Sphere", cyl: "Cyl", cone: "Cone", box: "Box" };
const ROLES = { "": "None", head: "Head", leg0: "Leg0", leg1: "Leg1", leg2: "Leg2", leg3: "Leg3", tail: "Tail", tailup: "TailUp", wing0: "Wing0", wing1: "Wing1" };

const out = [];
out.push("// Generated by game/Tools/gen-life-rigs.mjs from server/public/js/liferigs.js. Do not edit by hand.");
out.push("");

function emit(name, rig, vehicle) {
  out.push("{");
  out.push(`\tFEarthRig& R = Add(TEXT("${name}"), ${vehicle ? "true" : "false"});`);
  if (!vehicle) {
    out.push(`\tR.Voice = ${text(rig.voice)}; R.Alarm = ${text(rig.alarm)};`);
    out.push(`\tR.Alert = ${num(rig.alert)}; R.Flee = ${num(rig.flee)}; R.Stride = ${num(rig.stride)}; R.Graze = ${num(rig.graze)}; R.Drop = ${num(rig.drop)};`);
    out.push(`\tR.Neck = ${vec(rig.neck)};`);
    out.push(`\tR.bPeck = ${!!rig.peck}; R.Hop = ${num(rig.hop ?? 0)}; R.bSwim = ${rig.swim !== undefined}; R.Swim = ${num(rig.swim ?? 0)}; R.Waddle = ${num(rig.waddle ?? 0)};`);
    out.push(`\tR.TakesOff = ${num(rig.takesOff ?? 0)}; R.Curious = ${num(rig.curious ?? 0)}; R.bFly = ${!!rig.fly}; R.bFlock = ${!!rig.flock}; R.Yields = ${num(rig.yields ?? 0)}; R.Heel = ${num(rig.heel ?? 0)};`);
    if (rig.wing) {
      const w = rig.wing;
      out.push(`\tR.bWing = true; R.WingAir = ${vec(w.air)}; R.WingWalk = ${vec(w.walk)}; R.bWingStartled = ${!!w.startled}; R.WingStartled = ${vec(w.startled ?? [0, 0])}; R.WingRate = ${num(w.rate)};`);
    }
  }
  out.push(`\tR.Coats = { ${rig.coats.map(([a, b]) => `{ ${hex(a)}, ${hex(b)} }`).join(", ")} };`);
  out.push("\tR.Parts = {");
  for (const [shape, colour, at, size, role = "", tilt = 0] of rig.parts) {
    if (!SHAPES[shape] || ROLES[role] === undefined) throw new Error(`${name}: unknown shape or role ${shape} ${role}`);
    const c = colour === "a" ? "FEarthRigPart::CoatA" : colour === "b" ? "FEarthRigPart::CoatB" : hex(colour);
    out.push(`\t\t{ EEarthShape::${SHAPES[shape]}, ${c}, ${vec(at)}, ${vec(size)}, EEarthRole::${ROLES[role]}, ${num(tilt)} },`);
  }
  out.push("\t};");
  out.push("}");
}

for (const [name, rig] of Object.entries(RIGS)) emit(name, rig, false);
for (const [name, rig] of Object.entries(VEHICLES)) emit(name, rig, true);

const file = join(here, "../Source/EarthWalk/EarthLifeRigs.gen.inl");
writeFileSync(file, out.join("\n") + "\n");
console.log(`wrote ${file}: ${Object.keys(RIGS).length} animals and machines, ${Object.keys(VEHICLES).length} vehicles`);
